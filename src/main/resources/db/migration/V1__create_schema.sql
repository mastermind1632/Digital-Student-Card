-- Digital Student Card schema (PostgreSQL). Flyway runs this once; Hibernate only validates it.

CREATE TABLE student (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number  varchar(12)  NOT NULL UNIQUE,
    full_name       varchar(100) NOT NULL,
    id_number       varchar(13)  NOT NULL UNIQUE,
    birth_date      date,
    gender          varchar(10),
    nationality     varchar(40),
    email           varchar(120) NOT NULL UNIQUE,
    phone_number    varchar(20),
    campus          varchar(80),
    department      varchar(120),
    qualification   varchar(120),
    year_of_study   integer,
    password_hash   varchar(100) NOT NULL,
    status          varchar(12)  NOT NULL,
    status_reason   varchar(250),
    card_version    integer      NOT NULL,
    issue_date      date         NOT NULL,
    expiry_date     date         NOT NULL,
    has_photo       boolean      NOT NULL,
    created_at      timestamp(6) NOT NULL,
    updated_at      timestamp(6) NOT NULL,
    last_login_at   timestamp(6)
);
CREATE INDEX idx_student_status ON student (status);
CREATE INDEX idx_student_campus ON student (campus);
CREATE INDEX idx_student_lower_name ON student (lower(full_name));

-- Photos live in their own table so lists of students never load images.
CREATE TABLE student_photo (
    student_id    bigint       PRIMARY KEY REFERENCES student (id) ON DELETE CASCADE,
    content       bytea        NOT NULL,
    content_type  varchar(40)  NOT NULL,
    updated_at    timestamp(6) NOT NULL
);

CREATE TABLE staff_user (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       varchar(40)  NOT NULL UNIQUE,
    full_name      varchar(100) NOT NULL,
    password_hash  varchar(100) NOT NULL,
    role           varchar(12)  NOT NULL,
    active         boolean      NOT NULL,
    created_at     timestamp(6) NOT NULL,
    last_login_at  timestamp(6)
);

CREATE TABLE verification_log (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number  varchar(20),
    student_name    varchar(100),
    result          varchar(12)  NOT NULL,
    method          varchar(12)  NOT NULL,
    checked_by      varchar(60),
    location        varchar(80),
    ip_address      varchar(64),
    checked_at      timestamp(6) NOT NULL
);
CREATE INDEX idx_verification_student ON verification_log (student_number);
CREATE INDEX idx_verification_checked_at ON verification_log (checked_at);

CREATE TABLE audit_event (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor        varchar(60)   NOT NULL,
    action       varchar(60)   NOT NULL,
    target       varchar(60),
    details      varchar(1000),
    occurred_at  timestamp(6)  NOT NULL
);
CREATE INDEX idx_audit_target ON audit_event (target);

CREATE TABLE app_setting (
    setting_key    varchar(80)   PRIMARY KEY,
    setting_value  varchar(2000) NOT NULL
);
